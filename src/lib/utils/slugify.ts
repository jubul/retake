/** NFD + quitar diacríticos, lowercase, [^a-z0-9]+ → '-', trim de '-', máx 80 chars. '' si no queda nada. */
export function slugify(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80)
    .replace(/-+$/g, '');
}
